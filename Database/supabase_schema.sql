-- -----------------------------------------------------------------------------
-- 14. VISTA DE ALERTAS TEMPRANAS DE VENCIMIENTO
-- -----------------------------------------------------------------------------
CREATE OR REPLACE VIEW public.vista_alertas_vencimiento AS
SELECT
    d.id AS documento_id,
    d.asociacion_id,
    a.nombre AS asociacion,
    d.asociado_id,
    td.nombre AS tipo_documento,
    d.fecha_vencimiento,
    (d.fecha_vencimiento - CURRENT_DATE) AS dias_restantes,
    CASE
        WHEN d.fecha_vencimiento < CURRENT_DATE THEN 'vencido'::text
        WHEN d.fecha_vencimiento <= (CURRENT_DATE + 30) THEN 'por_vencer'::text
        ELSE 'vigente'::text
    END AS semaforo
FROM public.documentos d
JOIN public.asociaciones a ON a.id = d.asociacion_id
JOIN public.tipos_documento td ON td.id = d.tipo_documento_id
WHERE d.fecha_vencimiento IS NOT NULL;


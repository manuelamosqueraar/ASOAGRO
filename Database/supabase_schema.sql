-- -----------------------------------------------------------------------------
-- 2. TABLA: asociaciones (Espacio institucional independiente)
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.asociaciones (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre character varying NOT NULL,
    nit character varying,
    municipio character varying,
    representante_legal character varying,
    correo character varying,
    telefono character varying,
    activo boolean NOT NULL DEFAULT true,
    creado_en timestamp with time zone NOT NULL DEFAULT now()
);

ALTER TABLE public.asociaciones ADD COLUMN IF NOT EXISTS nit character varying;
ALTER TABLE public.asociaciones ADD COLUMN IF NOT EXISTS representante_legal character varying;
ALTER TABLE public.asociaciones ADD COLUMN IF NOT EXISTS correo character varying;
ALTER TABLE public.asociaciones ADD COLUMN IF NOT EXISTS telefono character varying;

-- -----------------------------------------------------------------------------
-- 3. TABLA: usuarios (Usuarios del sistema y roles de acceso)
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.usuarios (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_completo character varying NOT NULL,
    documento_id character varying NOT NULL UNIQUE,
    correo character varying NOT NULL UNIQUE,
    telefono character varying,
    contrasena_hash text,
    rol public.rol_usuario NOT NULL,
    asociacion_id integer REFERENCES public.asociaciones(id) ON DELETE SET NULL,
    activo boolean NOT NULL DEFAULT true,
    ultimo_acceso timestamp with time zone,
    creado_en timestamp with time zone NOT NULL DEFAULT now()
);

-- -----------------------------------------------------------------------------
-- 4. TABLA: asociados (Productores agrícolas afiliados)
-- -----------------------------------------------------------------------------

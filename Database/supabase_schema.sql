    estado_membresia character varying NOT NULL DEFAULT 'Activo',
    fecha_registro timestamp with time zone NOT NULL DEFAULT now(),
    fecha_actualizacion timestamp with time zone,
    creado_por character varying NOT NULL DEFAULT 'Sistema',
    actualizado_por character varying,
    finca_vereda character varying NOT NULL DEFAULT '',
    cultivo_principal character varying NOT NULL DEFAULT '',
    tiene_bpa boolean NOT NULL DEFAULT false

    titulo varchar(200) NOT NULL DEFAULT '',
    fecha timestamp with time zone NOT NULL DEFAULT now(),
    descripcion text NOT NULL DEFAULT '',
    archivo_nombre varchar(255) NOT NULL DEFAULT ''
);

-- Asegurar todas las columnas requeridas en public.actas si la tabla ya existía
DO $$
DECLARE
    col_rec record;
BEGIN
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema = 'public' AND table_name = 'actas' AND column_name = 'tipo') THEN
        ALTER TABLE public.actas ADD COLUMN tipo varchar(60) NOT NULL DEFAULT 'Acta de Asamblea';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema = 'public' AND table_name = 'actas' AND column_name = 'titulo') THEN
        ALTER TABLE public.actas ADD COLUMN titulo varchar(200) NOT NULL DEFAULT '';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema = 'public' AND table_name = 'actas' AND column_name = 'fecha') THEN
        ALTER TABLE public.actas ADD COLUMN fecha timestamp with time zone NOT NULL DEFAULT now();
    END IF;
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema = 'public' AND table_name = 'actas' AND column_name = 'descripcion') THEN
        ALTER TABLE public.actas ADD COLUMN descripcion text NOT NULL DEFAULT '';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema = 'public' AND table_name = 'actas' AND column_name = 'archivo_nombre') THEN
        ALTER TABLE public.actas ADD COLUMN archivo_nombre varchar(255) NOT NULL DEFAULT '';
    END IF;

    -- Permitir NULL en columnas preexistentes adicionales que no tengan DEFAULT
    FOR col_rec IN
        SELECT column_name
        FROM information_schema.columns
        WHERE table_schema = 'public'
          AND table_name = 'actas'
          AND is_nullable = 'NO'
          AND column_default IS NULL
          AND is_identity = 'NO'
          AND column_name NOT IN ('id', 'tipo', 'titulo', 'fecha', 'descripcion', 'archivo_nombre')
    LOOP
        EXECUTE format('ALTER TABLE public.actas ALTER COLUMN %I DROP NOT NULL', col_rec.column_name);
    END LOOP;
END $$;

CREATE INDEX IF NOT EXISTS ix_actas_tipo ON public.actas (tipo);

DO $$ BEGIN
    CREATE TYPE public.rol_usuario AS ENUM ('directora', 'secretaria', 'tesorero', 'presidente', 'administrador');
EXCEPTION
    WHEN duplicate_object THEN null;
END $$;

DO $$ BEGIN
    CREATE TYPE public.estado_documento AS ENUM ('vigente', 'por_vencer', 'vencido', 'en_tramite');
EXCEPTION
    WHEN duplicate_object THEN null;
END $$;

DO $$ BEGIN
    CREATE TYPE public.categoria_documento AS ENUM ('legal', 'tributario', 'institucional', 'productivo', 'social');
EXCEPTION
    WHEN duplicate_object THEN null;

-- 3. TABLA: documentos
-- =============================================================================
CREATE TABLE IF NOT EXISTS public.documentos (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asociado_id integer NOT NULL,
    tipo_documento_id integer NULL,
    documento_asociado varchar(20) NOT NULL DEFAULT '',
    tipo_documento varchar(120) NOT NULL DEFAULT '',
    archivo_nombre varchar(255) NOT NULL DEFAULT '',
    fecha_emision timestamp with time zone NOT NULL DEFAULT now(),
    fecha_vencimiento timestamp with time zone NULL,
    estado varchar(30) NOT NULL DEFAULT 'Vigente',
    CONSTRAINT fk_documentos_asociados FOREIGN KEY (asociado_id)
        REFERENCES public.asociados (id) ON DELETE CASCADE,
    CONSTRAINT fk_documentos_tipos_documento FOREIGN KEY (tipo_documento_id)
        REFERENCES public.tipos_documento (id) ON DELETE SET NULL
);

-- Asegurar todas las columnas requeridas en public.documentos si la tabla ya existía
DO $$
DECLARE
    v_asociado_id_type text;
    v_tipo_doc_id_type text;
    col_rec record;
BEGIN
    SELECT data_type INTO v_asociado_id_type
    FROM information_schema.columns
    WHERE table_schema = 'public' AND table_name = 'asociados' AND column_name = 'id';

    SELECT data_type INTO v_tipo_doc_id_type
    FROM information_schema.columns
    WHERE table_schema = 'public' AND table_name = 'tipos_documento' AND column_name = 'id';

    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema = 'public' AND table_name = 'documentos' AND column_name = 'asociado_id') THEN
        EXECUTE format('ALTER TABLE public.documentos ADD COLUMN asociado_id %s NULL', COALESCE(v_asociado_id_type, 'integer'));
    END IF;

    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema = 'public' AND table_name = 'documentos' AND column_name = 'tipo_documento_id') THEN
        EXECUTE format('ALTER TABLE public.documentos ADD COLUMN tipo_documento_id %s NULL', COALESCE(v_tipo_doc_id_type, 'integer'));
    END IF;

    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema = 'public' AND table_name = 'documentos' AND column_name = 'documento_asociado') THEN
        ALTER TABLE public.documentos ADD COLUMN documento_asociado varchar(20) NOT NULL DEFAULT '';
    END IF;

    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema = 'public' AND table_name = 'documentos' AND column_name = 'tipo_documento') THEN
        ALTER TABLE public.documentos ADD COLUMN tipo_documento varchar(120) NOT NULL DEFAULT '';
    END IF;

    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema = 'public' AND table_name = 'documentos' AND column_name = 'archivo_nombre') THEN
        ALTER TABLE public.documentos ADD COLUMN archivo_nombre varchar(255) NOT NULL DEFAULT '';
    END IF;

    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema = 'public' AND table_name = 'documentos' AND column_name = 'fecha_emision') THEN
        ALTER TABLE public.documentos ADD COLUMN fecha_emision timestamp with time zone NOT NULL DEFAULT now();
    END IF;

    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema = 'public' AND table_name = 'documentos' AND column_name = 'fecha_vencimiento') THEN
        ALTER TABLE public.documentos ADD COLUMN fecha_vencimiento timestamp with time zone NULL;
    END IF;

    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema = 'public' AND table_name = 'documentos' AND column_name = 'estado') THEN
        ALTER TABLE public.documentos ADD COLUMN estado varchar(30) NOT NULL DEFAULT 'Vigente';
    END IF;

    -- Si la tabla documentos preexistente tiene otras columnas NOT NULL sin valor por defecto,
    -- permitir NULL en ellas para no bloquear inserciones desde el modelo C# actual
    FOR col_rec IN
        SELECT column_name
        FROM information_schema.columns
        WHERE table_schema = 'public'
          AND table_name = 'documentos'
          AND is_nullable = 'NO'
          AND column_default IS NULL
          AND is_identity = 'NO'
          AND column_name NOT IN (
              'id', 'asociado_id', 'tipo_documento_id', 'documento_asociado',
              'tipo_documento', 'archivo_nombre', 'fecha_emision', 'fecha_vencimiento', 'estado'
          )
    LOOP
        EXECUTE format('ALTER TABLE public.documentos ALTER COLUMN %I DROP NOT NULL', col_rec.column_name);
    END LOOP;
END $$;

CREATE INDEX IF NOT EXISTS ix_documentos_asociado_id ON public.documentos (asociado_id);
CREATE INDEX IF NOT EXISTS ix_documentos_fecha_vencimiento ON public.documentos (fecha_vencimiento);


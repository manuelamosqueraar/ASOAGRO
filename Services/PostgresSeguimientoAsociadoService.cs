using Asoagro.Data;
using Asoagro.Models;
using Microsoft.EntityFrameworkCore;

namespace Asoagro.Services;

public class PostgresSeguimientoAsociadoService(
    IDbContextFactory<AsoagroDbContext> dbContextFactory) : ISeguimientoAsociadoService
{
    private readonly object syncSchema = new();
    private bool tablaVerificada;

    public bool UsaAlmacenamientoPermanente => true;

    private void AsegurarTabla(AsoagroDbContext context)
    {
        if (tablaVerificada) return;
        lock (syncSchema)
        {
            if (tablaVerificada) return;
            try
            {
                var strategy = context.Database.CreateExecutionStrategy();
                strategy.Execute(() =>
                {
                    context.Database.ExecuteSqlRaw("""
                        CREATE TABLE IF NOT EXISTS public.seguimientos_asociados (
                            id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            asociado_id integer NOT NULL,
                            tipo_gestion varchar(40) NOT NULL,
                            fecha_gestion timestamp with time zone NOT NULL DEFAULT now(),
                            descripcion varchar(1000) NOT NULL,
                            proxima_gestion date,
                            gestionado_por varchar(254) NOT NULL,
                            CONSTRAINT fk_seguimientos_asociados_asociado
                                FOREIGN KEY (asociado_id) REFERENCES public.asociados (id) ON DELETE CASCADE
                        );
                        CREATE INDEX IF NOT EXISTS ix_seguimientos_asociados_asociado_fecha
                            ON public.seguimientos_asociados (asociado_id, fecha_gestion DESC);
                        """);
                });
                tablaVerificada = true;
            }
            catch
            {
                // Si la tabla ya existe o hay latencia temporal, se intentará de nuevo en la siguiente llamada
            }
        }
    }

    public IReadOnlyCollection<SeguimientoAsociado> ObtenerTodos()
    {
        using var context = dbContextFactory.CreateDbContext();
        AsegurarTabla(context);
        return context.SeguimientosAsociados
            .AsNoTracking()
            .Include(seguimiento => seguimiento.Asociado)
            .OrderByDescending(seguimiento => seguimiento.FechaGestion)
            .ToList();
    }

    public ResultadoRegistroSeguimientoAsociado Registrar(SeguimientoAsociado seguimiento)
    {
        using var context = dbContextFactory.CreateDbContext();
        AsegurarTabla(context);
        if (!context.Asociados.Any(asociado => asociado.Id == seguimiento.AsociadoId))
        {
            return new ResultadoRegistroSeguimientoAsociado
            {
                Exitoso = false,
                Mensaje = "El asociado seleccionado ya no existe en el padrón."
            };
        }

        seguimiento.Id = 0;
        seguimiento.Asociado = null;
        seguimiento.FechaGestion = DateTime.UtcNow;
        context.SeguimientosAsociados.Add(seguimiento);
        context.SaveChanges();

        return new ResultadoRegistroSeguimientoAsociado
        {
            Exitoso = true,
            Mensaje = "La gestión quedó guardada en el historial."
        };
    }
}
